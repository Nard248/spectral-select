"""Write docs/me_attention/FROZEN_SPACES.md from the model registry (single source of truth)."""
from __future__ import annotations

from pathlib import Path

from me_attention.models.registry import MODELS, SWEEP_MODELS
from me_attention.preprocess import PREPROC_DEFAULT, PREPROC_SPACE
from me_attention.train import TRAIN_DEFAULT, TRAIN_SPACE

OUT = Path(__file__).resolve().parents[2] / "docs" / "me_attention" / "FROZEN_SPACES.md"


def main():
    L = ["# Frozen search spaces (auto-generated by `scripts/me_attention/dump_spaces.py` -- do not edit)", "",
         "Shared preprocessing space (all models): `%s`, default `%s`." % (PREPROC_SPACE, PREPROC_DEFAULT), "",
         "Shared neural training space: `%s`; fixed: `%s`." % (TRAIN_SPACE, {k: v for k, v in TRAIN_DEFAULT.items()
                                                                           if k not in TRAIN_SPACE}), "",
         "Scale augmentation semantics: per-pixel logU(0.7,1.4) scale on the raw input; exact no-op for norm != none "
         "(all norms are scale invariant), applied on-device for norm = none. `ex_drop` zeroes whole excitation blocks "
         "after preprocessing. Same code path for every neural model.", "",
         "| model | track | family | space | default |", "|---|---|---|---|---|"]
    for grp, names in SWEEP_MODELS.items():
        for n in names:
            s = MODELS[n]
            sp = "<br>".join(f"`{k}`: {v}" for k, v in s.space.items())
            df = ", ".join(f"{k}={v}" for k, v in s.default.items())
            L.append(f"| {n} | {s.track} | {s.family} | {sp} | {df} |")
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
